/**
 * «Рекламные баннеры» — рекламный креатив для перехода на сайт, а не слайд
 * внутри карточки маркетплейса. Отличие от инфографики принципиальное:
 * у баннера ЕСТЬ логотип, кнопка, цена и адрес сайта — всё то, что WB и Ozon
 * на карточке запрещают.
 *
 * Разделение труда (решение владельца 2026-09-10):
 *  - модель рисует сцену, товар и выразительный ЗАГОЛОВОК (запекает в картинку);
 *  - сайт поверх кладёт цену, кнопку, адрес и логотип — их можно менять
 *    бесплатно и мгновенно, без новой генерации.
 * Заголовок запечён, поэтому его правка = новая платная генерация. Интерфейс
 * обязан говорить об этом ДО списания генов, а не после.
 *
 * Pure module — используется и на клиенте (форма, превью), и на сервере.
 */

/** Оформление баннера. Совпадает по духу со стилями инфографики, но проще: три понятных варианта. */
export type BannerLook = "light" | "dark" | "bright";

export type BannerFormatId = "square" | "wide" | "story";

/** Что человек продаёт. Всё — дословно из формы: ничего не досочиняем. */
export type BannerOffer = {
  productName: string;
  /** главное преимущество одной строкой: «напиток остаётся горячим 8 часов» */
  benefit?: string;
  /** цена как ввёл человек: «990 ₽». Реклама — это ФЗ-38, цифра должна быть настоящей. */
  price?: string;
  /** старая цена для зачёркивания */
  oldPrice?: string;
};

/** Слой, который рисует САЙТ поверх картинки. Меняется без перегенерации. */
export type BannerOverlay = {
  price?: string;
  oldPrice?: string;
  /** текст кнопки: «Подробнее», «Купить», «Перейти» */
  cta?: string;
  /** адрес сайта — то, ради чего баннер и делается */
  site?: string;
  /** логотип пользователя, data URL */
  logo?: string;
};

/** Заголовок, который запечёт модель. Утверждается ДО генерации. */
export type BannerHeadline = {
  headline: string;
  /** вторая строка помельче, необязательна */
  subheadline?: string;
};

export type BannerInput = BannerOffer &
  BannerHeadline & {
    look: BannerLook;
    format: BannerFormatId;
  };

/** Что вернул сервер после генерации. */
export type BannerResult = {
  imageUrl: string;
  width: number;
  height: number;
};

export const CTA_PRESETS = ["Подробнее", "Купить", "Перейти на сайт", "Заказать", "Смотреть"];

export const LOOK_LABELS: Record<BannerLook, string> = {
  light: "Светлое",
  dark: "Тёмное",
  bright: "Яркое",
};
