/**
 * Сборка инструкции для «Улучшить карточку по советам ИИ».
 *
 * УРОК (2026-08-21): раньше мы склеивали ВСЕ советы анализа и отдавали их
 * картиночной модели. Советы написаны для человека-дизайнера и звучат как
 * «добавить плашку „Размеры S-XL“», «добавить инфографику с размерной сеткой
 * на одно из дополнительных фото». Модель честно пыталась выполнить: рисовала
 * кривую таблицу размеров и выдумывала английские надписи — русский текст она
 * рисовать не умеет, а «другое фото» в одном кадре сделать невозможно.
 *
 * Правило теперь такое: модель редактирования отвечает ТОЛЬКО за то, что она
 * реально умеет — свет, фон, композицию, чистоту кадра. Всё, что про текст,
 * плашки и размерные сетки, уходит в раздел «Инфографика», где русский текст
 * впекает gpt-image по выверенной типографике.
 *
 * Pure-модуль: используется и на клиенте (страница анализа), и на сервере.
 */

/** советы про текст, плашки, шрифты — картиночной модели не отдаём */
const TEXTUAL =
  /текст|надпис|плашк|инфограф|размерн|таблиц|шрифт|заголов|подпис|логотип|бейдж|значок|иконк|стикер|бирк|ценник|скидк|призыв|cta/i;

/** советы про другие кадры карусели — в одном изображении невыполнимы */
const OTHER_SHOT =
  /допол\w*\s+фото|втор\w*\s+фото|друг\w*\s+фото|ещё\s+фото|карусел|слайд|видео|отзыв/i;

export type AdviceSplit = {
  /** что можно поручить модели редактирования изображения */
  visual: string[];
  /** что нужно делать в «Инфографике» или вручную */
  textual: string[];
};

export function splitAdvice(items: (string | undefined)[]): AdviceSplit {
  const visual: string[] = [];
  const textual: string[] = [];
  for (const raw of items) {
    const item = raw?.trim();
    if (!item) continue;
    if (TEXTUAL.test(item) || OTHER_SHOT.test(item)) textual.push(item);
    else visual.push(item);
  }
  return { visual, textual };
}

/** если визуальных советов не нашлось — улучшаем подачу по умолчанию */
const DEFAULT_VISUAL =
  "сделать фон чище и дороже, убрать лишние предметы из кадра, выровнять композицию";

/**
 * Инструкция построена ПОЗИТИВНО: перечисляем, что сохраняется и что меняется,
 * вместо списка запретов. Запрет вида «не добавляй текст» модель воспринимает
 * как упоминание текста — тот же урок, что и с видео.
 */
export function buildImprovePrompt(split: AdviceSplit): string {
  const changes = split.visual.slice(0, 3).join("; ") || DEFAULT_VISUAL;
  return (
    `Улучши подачу этого товара для карточки маркетплейса. ` +
    `Товар остаётся прежним: та же вещь, тот же цвет, тот же материал, те же детали и пропорции. ` +
    `Меняются только съёмка и окружение: ${changes}. ` +
    `Премиальная предметная съёмка, чистый однородный фон, мягкий студийный свет, ` +
    `товар крупно и в фокусе, сверху остаётся свободное поле под заголовок.`
  );
}
