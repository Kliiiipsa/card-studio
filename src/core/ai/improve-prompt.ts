/**
 * Сборка инструкции для «Улучшить карточку по советам ИИ».
 *
 * УРОК (2026-08-21): раньше мы склеивали ВСЕ советы анализа и отдавали их
 * картиночной модели. Советы написаны для человека-дизайнера и звучат как
 * «добавить плашку „Размеры S-XL“», «добавить инфографику с размерной сеткой
 * на одно из дополнительных фото». Модель честно пыталась выполнить: рисовала
 * кривую таблицу размеров и выдумывала английские надписи — русский текст она
 * рисовать не умеет, а «другое фото» в одном кадре сделать невозможно.
 *
 * Правило теперь такое: модель редактирования отвечает ТОЛЬКО за то, что она
 * реально умеет — свет, фон, композицию, чистоту кадра. Всё, что про текст,
 * плашки и размерные сетки, уходит в раздел «Инфографика», где русский текст
 * впекает gpt-image по выверенной типографике.
 *
 * Pure-модуль: используется и на клиенте (страница анализа), и на сервере.
 */

/** советы про текст, плашки, шрифты — картиночной модели не отдаём */
const TEXTUAL =
  /текст|надпис|плашк|инфограф|размерн|таблиц|шрифт|заголов|подпис|логотип|бейдж|значок|иконк|стикер|бирк|ценник|скидк|призыв|cta/i;

/**
 * Советы про другие кадры карусели — в одном изображении невыполнимы.
 *
 * ВНИМАНИЕ: `\w` в JavaScript — это [A-Za-z0-9_], кириллицу он НЕ покрывает,
 * поэтому «допол\w*\s+фото» не находило «дополнительных фото». Здесь и ниже
 * используем \p{L} с флагом u.
 */
const OTHER_SHOT =
  /(?:дополнительн|втор|друг|ещ[ёе])\p{L}*\s+фото|карусел|слайд|видео|отзыв/iu;

/**
 * Исключения: просьба ОСТАВИТЬ пустое место под заголовок — наоборот, полезна.
 * Без этого фильтр резал нашу же фразу «место под заголовок» из-за слова
 * «заголовок» и промпт становился пустым.
 */
const ALLOW =
  /(?:мест|пол|зон|пространств)\p{L}*\s+(?:под|для)\s+заголов|свободн\p{L}*\s+(?:мест|пол|зон)/iu;

export type AdviceSplit = {
  /** что можно поручить модели редактирования изображения */
  visual: string[];
  /** что нужно делать в «Инфографике» или вручную */
  textual: string[];
};

export function splitAdvice(items: (string | undefined)[]): AdviceSplit {
  const visual: string[] = [];
  const textual: string[] = [];
  for (const raw of items) {
    const item = raw?.trim();
    if (!item) continue;
    if (!ALLOW.test(item) && (TEXTUAL.test(item) || OTHER_SHOT.test(item))) textual.push(item);
    else visual.push(item);
  }
  return { visual, textual };
}

/**
 * Серверный предохранитель: вырезает из ЛЮБОГО пришедшего промпта требования
 * дорисовать плашки, надписи и размерные сетки.
 *
 * Зачем, если фильтр уже есть на клиенте: инструкция собирается в браузере, и
 * у пользователя со старой вкладкой остаётся старый код — 2026-08-21 именно
 * так уже случилось, исправление было на проде, а запрос ушёл прежний.
 * Сервер — единственное место, которое нельзя обойти устаревшей вкладкой.
 */
export function sanitizeImagePrompt(prompt: string): string {
  // режем по предложениям: точка с запятой и точка — наши разделители советов
  const parts = prompt
    .split(/(?<=[.;])\s+/)
    .map((s) => s.trim())
    .filter(Boolean);
  const kept = parts.filter((s) => ALLOW.test(s) || (!TEXTUAL.test(s) && !OTHER_SHOT.test(s)));
  // если после чистки не осталось смысла — берём нейтральную инструкцию
  if (!kept.length) return buildImprovePrompt({ visual: [], textual: [] });
  return kept.join(" ");
}

/**
 * v2 (разбор журнала 2026-09-06): те же классы советов, но по границам слов.
 * Старые регулярки ловили подстроки: /текст/ → «текстура», «контекст»;
 * /заголов/ → нашу же фразу «пространство сверху для заголовка» (ALLOW не
 * узнавала слово «сверху» между ними). Так резалось описание товара у 84 из
 * 115 генераций. Применяется только под гейтом photoFixEnabled и только к
 * потоку «Улучшить по советам» — промпт из раздела «Фото товара» не режем:
 * что человек видит в поле, то и уходит в модель.
 */
const TEXTUAL_V2 =
  /(?<!\p{L})(?:текст(?!ур)|надпис|плашк|инфограф|размерн|таблиц|шрифт|заголов|подпис|логотип|бейдж|значок|иконк|стикер|бирк|ценник|скидк|призыв|cta)/iu;
const ALLOW_V2 =
  /(?:под|для)(?:\s+\p{L}+){0,2}\s+(?:заголов|текст(?!ур))|свободн\p{L}*\s+(?:мест|пол|зон)/iu;

export function sanitizeImagePromptV2(prompt: string): string {
  const parts = prompt
    .split(/(?<=[.;])\s+/)
    .map((s) => s.trim())
    .filter(Boolean);
  const kept = parts.filter((s) => ALLOW_V2.test(s) || (!TEXTUAL_V2.test(s) && !OTHER_SHOT.test(s)));
  if (!kept.length) return buildImprovePrompt({ visual: [], textual: [] });
  return kept.join(" ");
}

/** если визуальных советов не нашлось — улучшаем подачу по умолчанию */
const DEFAULT_VISUAL =
  "сделать фон чище и дороже, убрать лишние предметы из кадра, выровнять композицию";

/**
 * Инструкция построена ПОЗИТИВНО: перечисляем, что сохраняется и что меняется,
 * вместо списка запретов. Запрет вида «не добавляй текст» модель воспринимает
 * как упоминание текста — тот же урок, что и с видео.
 */
export function buildImprovePrompt(split: AdviceSplit): string {
  const changes = split.visual.slice(0, 3).join("; ") || DEFAULT_VISUAL;
  return (
    `Улучши подачу этого товара для карточки маркетплейса. ` +
    `Товар остаётся прежним: та же вещь, тот же цвет, тот же материал, те же детали и пропорции. ` +
    `Меняются только съёмка и окружение: ${changes}. ` +
    `Премиальная предметная съёмка, чистый однородный фон, мягкий студийный свет, ` +
    `товар крупно и в фокусе, сверху остаётся свободное поле под заголовок.`
  );
}
